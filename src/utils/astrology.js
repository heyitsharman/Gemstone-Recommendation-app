export function getZodiacSign(dobString) {
  if (!dobString) return "Scorpio"; // default fallback
  const date = new Date(dobString);
  if (isNaN(date.getTime())) return "Scorpio";
  
  const month = date.getMonth() + 1; // 1-12
  const day = date.getDate(); // 1-31

  if ((month === 3 && day >= 21) || (month === 4 && day <= 19)) return "Aries";
  if ((month === 4 && day >= 20) || (month === 5 && day <= 20)) return "Taurus";
  if ((month === 5 && day >= 21) || (month === 6 && day <= 20)) return "Gemini";
  if ((month === 6 && day >= 21) || (month === 7 && day <= 22)) return "Cancer";
  if ((month === 7 && day >= 23) || (month === 8 && day <= 22)) return "Leo";
  if ((month === 8 && day >= 23) || (month === 9 && day <= 22)) return "Virgo";
  if ((month === 9 && day >= 23) || (month === 10 && day <= 22)) return "Libra";
  if ((month === 10 && day >= 23) || (month === 11 && day <= 21)) return "Scorpio";
  if ((month === 11 && day >= 22) || (month === 12 && day <= 21)) return "Sagittarius";
  if ((month === 12 && day >= 22) || (month === 1 && day <= 19)) return "Capricorn";
  if ((month === 1 && day >= 20) || (month === 2 && day <= 18)) return "Aquarius";
  if ((month === 2 && day >= 19) || (month === 3 && day <= 20)) return "Pisces";
  
  return "Scorpio";
}

export function getRecommendations(name, zodiac, purpose, metalPrefs) {
  // Find primary
  let possible = gemstones.filter(g => g.zodiacs.includes(zodiac));
  if (possible.length === 0) {
    possible = gemstones; // fallback
  }

  // Choose the gemstone based on purpose and zodiac compatibility
  let primary = possible[0];
  const purposeLower = (purpose || "").toLowerCase();
  
  if (purposeLower.includes("career") || purposeLower.includes("ambition") || purposeLower.includes("focus")) {
    primary = possible.find(g => ["Saturn", "Sun", "Mars"].includes(g.planet)) || possible[0];
  } else if (purposeLower.includes("wealth") || purposeLower.includes("abundance") || purposeLower.includes("prosperity")) {
    primary = possible.find(g => ["Jupiter", "Mercury"].includes(g.planet)) || possible[0];
  } else if (purposeLower.includes("relationship") || purposeLower.includes("marriage") || purposeLower.includes("love")) {
    primary = possible.find(g => ["Venus", "Moon"].includes(g.planet)) || possible[0];
  } else if (purposeLower.includes("health") || purposeLower.includes("vitality") || purposeLower.includes("courage")) {
    primary = possible.find(g => ["Mars", "Sun"].includes(g.planet)) || possible[0];
  } else if (purposeLower.includes("wisdom") || purposeLower.includes("education")) {
    primary = possible.find(g => ["Jupiter", "Mercury"].includes(g.planet)) || possible[0];
  }

  // Calculate an organic-looking compatibility score (95% - 99%)
  let sum = 0;
  const safeName = name || "Alexander Thorne";
  for (let i = 0; i < safeName.length; i++) {
    sum += safeName.charCodeAt(i);
  }
  const compatibility = 95 + (sum % 5); // 95, 96, 97, 98, or 99

  // Get secondary alignments (excluding primary)
  const secondaryCandidates = gemstones.filter(g => g.id !== primary.id);
  secondaryCandidates.sort((a, b) => {
    const aZodiacMatch = a.zodiacs.includes(zodiac) ? 1 : 0;
    const bZodiacMatch = b.zodiacs.includes(zodiac) ? 1 : 0;
    if (aZodiacMatch !== bZodiacMatch) return bZodiacMatch - aZodiacMatch;
    
    const aPlanetMatch = a.planet === primary.planet ? 1 : 0;
    const bPlanetMatch = b.planet === primary.planet ? 1 : 0;
    return bPlanetMatch - aPlanetMatch;
  });

  const secondary = [
    { gem: secondaryCandidates[0], compatibility: compatibility - 10 - (sum % 3) },
    { gem: secondaryCandidates[1], compatibility: compatibility - 20 - (sum % 4) },
    { gem: secondaryCandidates[2], compatibility: compatibility - 28 - (sum % 2) }
  ];

  let wearingMetal = primary.metal;
  if (metalPrefs && metalPrefs.length > 0) {
    wearingMetal = metalPrefs.join(" / ");
  }

  return {
    primary,
    compatibility,
    secondary,
    wearingDetails: {
      finger: primary.finger,
      metal: wearingMetal,
      day: primary.day,
      weight: primary.weight,
      benefits: primary.benefits
    }
  };
}
